SOURCE = FEEDBACK / "feedback-walk-flow-test.mp4"
SOURCE_SHA256 = "7c644df616db66b7a3bd7747ddf27f65479e156cf2a869bd11598f74e8794011"
WORK = Path("/tmp/feedback-keypose-frames")

# Frame spec: one uniform scale and one floor line for every key.
PANEL_W, PANEL_H = 460, 620
FLOOR_Y = 560
TARGET_HEIGHT = 460
SOURCE_FPS = 30
HOLD_FRAMES = 5          # pose-to-pose: every key is held, no inbetweens
OUT_FPS = 30
CYCLES = 4
BG = (23, 25, 29)
FLOOR_COLOR = (58, 63, 71)


# ---------------------------------------------------------------- source frames

def extract_frames(first: int = 130, last: int = 238) -> None:
    ffmpeg = os.environ.get("FFMPEG", "ffmpeg")
    if WORK.exists() and len(list(WORK.glob("f*.png"))) >= last - first + 1:
        return
    WORK.mkdir(parents=True, exist_ok=True)
    pattern = str(WORK / "f%03d.png")
    subprocess.run(
        [ffmpeg, "-v", "error", "-y", "-i", str(SOURCE),
         "-vf", f"select='between(n\\,{first - 1}\\,{last - 1})',setpts=N/FRAME_RATE/TB",
         "-vsync", "0", "-start_number", str(first), pattern],
        check=True,
    )


def load_frame(n: int) -> np.ndarray:
    return np.asarray(Image.open(WORK / f"f{n:03d}.png").convert("RGB")).astype(np.int16)


# --------------------------------------------------------------------- keying

def keyed(frame: np.ndarray) -> tuple[np.ndarray, np.ndarray, dict]:
    """Return (rgba uint8, solid mask, cleanup stats) for one source frame.

    The clip's backdrop is flat neutral 238. Pixels that are both very light and
    neutral are dropped, which also eats the light halo that the source encode
    leaves around the shoes and the cable. A cream sole or a jacket stripe is not
    neutral enough to be dropped.
    """
    fm = frame.astype(np.int16)
    mn = fm.min(2)
    mx = fm.max(2)
    light_neutral = (mn > 222) & ((mx - mn) < 12)
    alpha = (~light_neutral).astype(np.uint8)

    # White/light scraps: detached specks and thin light fringes around the
    # figure. Drop every component that is not the body or the cable.
    lab, n = ndimage.label(alpha)
    if n:
        sizes = ndimage.sum(alpha, lab, range(1, n + 1))
        keep = np.zeros(n + 1, bool)
        keep[1:] = sizes >= 40
        alpha = keep[lab]

    # One-pixel halo pass: any pixel that is still nearly backdrop inside one
    # pixel of transparency is spill, not artwork.
    near_bg = (mn > 205) & ((mx - mn) < 16)
    ring = ndimage.binary_dilation(alpha == 0, iterations=1)
    spill = near_bg & (alpha == 1) & ring
    alpha = alpha & (~spill)

    # Small median on the label to close pinholes, then feather.
    alpha = ndimage.binary_closing(alpha, iterations=1).astype(np.uint8)
    soft = ndimage.gaussian_filter(alpha.astype(np.float32), 0.6)

    # Colour decontamination: the feathered ring takes its colour from the
    # nearest fully opaque pixel, never from the light backdrop.
    idx = ndimage.distance_transform_edt(
        alpha == 0, return_distances=False, return_indices=True
    )
    rgb = fm[tuple(idx)].astype(np.uint8)

    rgba = np.dstack([rgb, (np.clip(soft, 0, 1) * 255).astype(np.uint8)])
    solid = soft > 0.5

    white_scraps = int(
        ((alpha == 1) & (mn > 195) & ((mx - mn) < 18)).sum()
    )
    stats = {
        "opaquePx": int(alpha.sum()),
        "lightNeutralInsideFigurePx": white_scraps,
        "removedSpecks": int(n - keep.sum()) if n else 0,
        "spillPx": int(spill.sum()),
    }
    return rgba, solid, stats


def place(rgba: np.ndarray, solid: np.ndarray, scale: float, offset_x: float,
          sole_y: int) -> tuple[Image.Image, dict]:
    """Uniformly scale, pin the lowest sole to FLOOR_Y, place on the panel.

    offset_x is one constant for the whole stride, so the body's own lateral
    weight shift is kept instead of being centred away frame by frame.
    """
    h, w = solid.shape
    new_w, new_h = int(round(w * scale)), int(round(h * scale))
    im = Image.fromarray(rgba).resize((new_w, new_h), Image.LANCZOS)
    py = FLOOR_Y - sole_y * scale
    panel = Image.new("RGBA", (PANEL_W, PANEL_H), (0, 0, 0, 0))
    panel.alpha_composite(im, (int(round(offset_x)), int(round(py))))
    return panel, {"offsetX": offset_x, "py": py}


def measure(solid: np.ndarray) -> dict:
    ys, xs = np.nonzero(solid)
    sole = int(ys.max())
    top = int(ys.min())
    # Ankle band: relative to the sole so it follows the foot, not the canvas.
    band = solid[max(0, sole - 48): max(1, sole - 6)]
    by, bx = np.nonzero(band)
    span = int(bx.max() - bx.min() + 1) if bx.size else 0
    # Hip and shoulder centroids from narrow horizontal bands of the figure.
    height = sole - top
    def band_cx(lo: float, hi: float) -> float:
        a = solid[top + int(height * lo): top + int(height * hi)]
        yy, xx = np.nonzero(a)
        return float(xx.mean()) if xx.size else float(xs.mean())
    return {
        "soleY": sole,
        "headY": top,
        "height": height,
        "ankleSpan": span,
        "bodyCx": float((xs.min() + xs.max() + 1) / 2),
        "shoulderCx": band_cx(0.20, 0.30),
        "hipCx": band_cx(0.48, 0.56),
    }


# ------------------------------------------------------------------ analysis

def analyze() -> None:
    extract_frames()
    rows = {}
    for n in range(130, 239):
        rgba, solid, stats = keyed(load_frame(n))
        m = measure(solid)
        m["stats"] = stats
        rows[n] = m
    h = [rows[n]["height"] for n in rows]
    print("height range", min(h), max(h))
    print("frame  sole  top  hgt  span  bodyCx  shoCx  hipCx  sh-hip")
    for n in range(145, 201):
        m = rows[n]
        print(f"{n:5d} {m['soleY']:5d} {m['headY']:4d} {m['height']:4d} "
              f"{m['ankleSpan']:5d} {m['bodyCx']:7.1f} {m['shoulderCx']:6.1f} "
              f"{m['hipCx']:6.1f} {m['shoulderCx'] - m['hipCx']:6.1f}")

    # Loop closure: aligned composite difference between first and last frame
    # of a candidate span, so the seam is judged on what actually loops.
    scale = TARGET_HEIGHT / float(np.median([rows[n]["height"] for n in range(150, 200)]))
    print("\nclosure candidates (scaled, floor-aligned, same horizontal anchor)")
    best = []
    for length in range(38, 50):
        for start in range(145, 172):
            end = start + length - 1
            if end > 238:
                continue
            a, sa, _ = keyed(load_frame(start))
            b, sb, _ = keyed(load_frame(end))
            pa, _ = place(a, sa, scale, 0.0, rows[start]["soleY"])
            pb, _ = place(b, sb, scale, 0.0, rows[end]["soleY"])
            aa = np.asarray(pa).astype(np.int16)
            bb = np.asarray(pb).astype(np.int16)
            va = aa[:, :, 3] > 8
            vb = bb[:, :, 3] > 8
            union = va | vb
            d = np.abs(aa[:, :, :3] - bb[:, :, :3]).max(2)
            score = float(d[union].mean()) if union.any() else 999
            best.append((score, start, length, end))
    best.sort()
    for s in best[:8]:
        print(f"  score {s[0]:6.2f}  start f{s[1]}  length {s[2]}  end f{s[3]}")


# --------------------------------------------------------------------- build

def full_cycle(start: int, length: int):
    """Return aligned panels + metrics for a span, with uniform scale."""
    frames = [start + i for i in range(length)]
    keyed_frames = [(n,) + keyed(load_frame(n)) for n in frames]
    heights = [measure(s)["height"] for _, _, s, _ in keyed_frames]
    scale = TARGET_HEIGHT / float(np.median(heights))
    centres = [measure(s)["bodyCx"] for _, _, s, _ in keyed_frames]
    anchor = float(np.mean(centres))
    offset_x = PANEL_W / 2 - anchor * scale
    out = []
    for n, rgba, solid, stats in keyed_frames:
        m = measure(solid)
        panel, _ = place(rgba, solid, scale, offset_x, m["soleY"])
        out.append((n, panel, m, stats))
    return out, scale, anchor


def pick_keys(cycle, n_keys=8):
    """Sample eight evenly phased poses across the stride.

    The clip has no designed contact/down/pass/up drawings, so the keys are an
    even phase sample starting on the widest stance. Each key is labelled from
    its own measured stance, not from an assumed canonical beat.
    """
    n = len(cycle)
    metrics = [c[2] for c in cycle]
    spans = [m["ankleSpan"] for m in metrics]
    span_hi = min(spans) + (max(spans) - min(spans)) * 2 / 3
    span_lo = min(spans) + (max(spans) - min(spans)) / 3
    heights = [m["height"] for m in metrics]
    hgt_med = float(np.median(heights))
    out = []
    for j in range(n_keys):
        i = int(round(j * n / n_keys)) % n
        m = metrics[i]
        if m["ankleSpan"] >= span_hi:
            stance = "wide stance"
        elif m["ankleSpan"] <= span_lo:
            stance = "legs passing"
        else:
            stance = "mid-stride"
        out.append((i, stance, "above median" if m["height"] >= hgt_med else "below median"))
    return out


def draw_floor(panel: Image.Image) -> Image.Image:
    base = Image.new("RGBA", panel.size, BG + (255,))
    base.alpha_composite(panel)
    d = ImageDraw.Draw(base)
    d.line([(18, FLOOR_Y), (PANEL_W - 18, FLOOR_Y)], fill=FLOOR_COLOR + (255,), width=2)
    return base


def font(size: int, bold: bool = False):
    """Real TTF where one exists (a bitmap fallback drops spaces and dashes)."""
    name = "DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"
    candidates = [
        Path("/usr/share/fonts/truetype/dejavu") / name,
        Path("/usr/share/fonts/TTF") / name,
        Path("/usr/share/fonts/dejavu") / name,
    ]
    try:
        import matplotlib
        candidates.append(Path(matplotlib.__file__).parent / "mpl-data" / "fonts" / "ttf" / name)
    except Exception:
        pass
    for path in candidates:
        if path.exists():
            return ImageFont.truetype(str(path), size)
    return ImageFont.load_default(size=size)


def wrap(draw, text: str, fnt, width: int) -> list[str]:
    words, line, lines = text.split(), "", []
    for w in words:
        probe = (line + " " + w).strip()
        if draw.textlength(probe, font=fnt) > width and line:
            lines.append(line)
            line = w
        else:
            line = probe
    if line:
        lines.append(line)
    return lines


def build() -> None:
    extract_frames()
    # Contact-to-contact: widest stance at f148, next at f171, closing at f193.
    start, length = 148, 46
    cycle, scale, anchor = full_cycle(start, length)
    keys = pick_keys(cycle)
    assert len(keys) == 8, keys

    (HERE / "keys").mkdir(exist_ok=True)
    entries = []
    for idx, (ci, stance, level) in enumerate(keys):
        src, panel, m, stats = cycle[ci]
        filename = f"keys/key-{idx:02d}.png"
        panel.save(HERE / filename)
        heights = [c[2]["height"] for c in cycle]
        entries.append({
            "index": idx,
            "file": filename,
            "phase": stance,
            "level": level,
            "srcFrame": src,
            "srcTimeSec": round((src - 1) / SOURCE_FPS, 3),
            "ankleSpanPx": m["ankleSpan"],
            "figureHeightPx": m["height"],
            "heightVsLoopMedianPx": m["height"] - int(np.median(heights)),
            "bodyCxSrcPx": round(m["bodyCx"], 1),
            "shoulderHipOffsetPx": round(m["shoulderCx"] - m["hipCx"], 1),
            "cleanup": stats,
        })

    # --- pose sheet -------------------------------------------------------
    cell_w, cell_h = 300, 470
    cols, rows_n = 4, 2
    margin, header, footer = 46, 150, 150
    sheet = Image.new("RGB", (margin * 2 + cols * cell_w, header + rows_n * cell_h + footer), (16, 18, 22))
    d = ImageDraw.Draw(sheet)
    d.text((margin, 34), "FEEDBACK — rough walk key poses (extracted, not redrawn)", font=font(30, True), fill=(240, 240, 240))
    d.text((margin, 76), f"8 evenly phased keys over source frames {start}–{start + length - 1} · uniform scale {scale:.3f} · sole pinned to one floor line · step-and-hold",
           font=font(15), fill=(170, 176, 186))
    d.text((margin, 100), "Mic: anatomical LEFT hand in all 8 keys (near-arm free). No mirroring. Action/taunt poses are kept out of this sheet.",
           font=font(15), fill=(170, 176, 186))

    for i, e in enumerate(entries):
        col, row = i % cols, i // cols
        x = margin + col * cell_w
        y = header + row * cell_h
        panel = Image.open(HERE / e["file"]).convert("RGBA")
        thumb = panel.resize((int(PANEL_W * 0.58), int(PANEL_H * 0.58)), Image.LANCZOS)
        frame = Image.new("RGBA", thumb.size, BG + (255,))
        frame.alpha_composite(thumb)
        dd = ImageDraw.Draw(frame)
        dd.line([(14, FLOOR_Y * 0.58), (thumb.width - 14, FLOOR_Y * 0.58)], fill=FLOOR_COLOR, width=1)
        sheet.paste(frame.convert("RGB"), (x, y))
        d.rectangle([x, y, x + thumb.width, y + thumb.height], outline=(48, 52, 60))
        ty = y + thumb.height + 8
        d.text((x + 4, ty), f"{e['index'] + 1:02d}  {e['phase'].upper()}", font=font(17, True), fill=(236, 236, 236))
        d.text((x + 4, ty + 24), f"src f{e['srcFrame']}  t={e['srcTimeSec']:.2f}s  ·  {e['level']}", font=font(13), fill=(150, 156, 166))
        d.text((x + 4, ty + 42), f"ankle span {e['ankleSpanPx']}px  height {e['heightVsLoopMedianPx']:+d}px", font=font(13), fill=(150, 156, 166))
        d.text((x + 4, ty + 60), f"shoulder−hip {e['shoulderHipOffsetPx']:+.1f}px", font=font(13), fill=(150, 156, 166))

    fy = header + rows_n * cell_h + 6
    footer_font = font(14)
    footer = ("Evenly sampled poses, not designed contact/down/pass/up drawings. Real here: timing, weight shift, body bounce, "
              "foot placement, the existing lean. Missing: chin lift, amplified shoulder/hip bounce, free-arm swing, "
              "exaggerated heel lift / foot plants, cable consistency. Those need new drawings (see swagger-gap-sheet.png).")
    for k, line in enumerate(wrap(d, footer, footer_font, margin * 2 + cols * cell_w - margin * 2)):
        d.text((margin, fy + k * 19), line, font=footer_font, fill=(196, 160, 120))
    sheet.save(HERE / "pose-sheet-walk-keys.png")

    # --- swagger gap sheet ------------------------------------------------
    gap = Image.new("RGB", (1280, 760), (16, 18, 22))
    g = ImageDraw.Draw(gap)
    g.text((46, 34), "FEEDBACK walk — swagger brief vs. what extraction can honestly deliver", font=font(28, True), fill=(240, 240, 240))
    height_range = max(e["figureHeightPx"] for e in entries) - min(e["figureHeightPx"] for e in entries)
    sway = max(e["bodyCxSrcPx"] for e in entries) - min(e["bodyCxSrcPx"] for e in entries)
    offs = [e["shoulderHipOffsetPx"] for e in entries]
    g.text((46, 74), f"Source: feedback-walk-flow-test.mp4, frames {start}–{start + length - 1}. "
                     f"Asset-only pass: no model generation, no mirroring, no gameplay hookup.", font=font(14), fill=(160, 166, 176))
    g.text((46, 96), f"Measured in these 8 keys — body height range {height_range} px, lateral body-centre swing {sway:.1f} px, "
                     f"shoulder−hip offset {min(offs):+.1f} to {max(offs):+.1f} px.", font=font(14), fill=(160, 166, 176))
    rows_spec = [
        ("Chin higher + confident lean", "PARTIAL", "Existing lean/head angle only. Lifting the chin means redrawing the head, neck and collar."),
        ("More shoulder + hip bounce", "NOT PRESENT", "Body height moves only 10 px across these keys. Amplifying it would float or sink the planted foot unless the legs are redrawn."),
        ("Clear free-arm swing", "NOT PRESENT", "Free (near) arm hangs ~static through the stride; no swing keys exist in the clip."),
        ("Heel lifts + foot plants", "PARTIAL", "Toe-off shape exists in some source frames; lifting the heel higher needs new feet."),
        ("Mic in anatomical LEFT hand", "PASS", "Near arm is free; mic + coil sit on the far arm = his left. Same hand in 8/8 keys, idle matches. No mirror used."),
        ("Continuous cable", "PARTIAL", "Cable is continuous but the free end is drawn inconsistently (plug vs bare strand) and picks up a light halo."),
    ]
    y = 142
    g.text((46, y), "BRIEF ITEM", font=font(13, True), fill=(120, 126, 138))
    g.text((420, y), "STATUS", font=font(13, True), fill=(120, 126, 138))
    g.text((560, y), "EVIDENCE", font=font(13, True), fill=(120, 126, 138))
    y += 26
    colors = {"PASS": (120, 200, 140), "PARTIAL": (226, 178, 92), "NOT PRESENT": (226, 110, 110)}
    for item, status, ev in rows_spec:
        g.line([(46, y - 6), (1234, y - 6)], fill=(40, 44, 52))
        g.text((46, y + 4), item, font=font(16, True), fill=(226, 226, 226))
        g.text((420, y + 4), status, font=font(15, True), fill=colors[status])
        # wrapped evidence, 650 px column
        ev_lines = wrap(g, ev, font(13), 650)
        for k, ln in enumerate(ev_lines):
            g.text((560, y + 4 + k * 18), ln, font=font(13), fill=(176, 182, 192))
        y += max(48, 26 + 18 * len(ev_lines))

    g.text((46, y + 10), "NEW DRAWINGS REQUIRED (6 redraw sets, on top of these 8 extracted keys):", font=font(16, True), fill=(240, 210, 140))
    needs = [
        "A  head/neck: chin-up 8-key set (hat, dreads, concealed eyes unchanged; jaw + collar redrawn).",
        "B  torso: shoulder line counter-rotated against hips, +6–8 px vertical bounce per key, 3/4 lean held.",
        "C  free (near/right) arm: 4 swing positions — back, low, forward, high — elbow soft, hand open.",
        "D  feet: 2 heel-lift toe-off keys and 2 flat plant keys, Clarks last and size identical (same sole length).",
        "E  cable: one continuous path, fixed plug height, redrawn where the coil meets the wrist.",
        "F  cleanup: redraw shoe/cable edges on a transparent canvas (no light fringe) rather than keying an encode.",
    ]
    for i, nline in enumerate(needs):
        g.text((46, y + 44 + i * 24), f"{i + 1}. {nline}", font=font(14), fill=(196, 202, 212))
    gap.save(HERE / "swagger-gap-sheet.png")

    # --- MP4 + seam -------------------------------------------------------
    seq = [Image.open(HERE / e["file"]).convert("RGBA") for e in entries]
    frames = []
    for _ in range(CYCLES):
        for panel in seq:
            f = draw_floor(panel)
            for _ in range(HOLD_FRAMES):
                frames.append(f.convert("RGB"))

    ffmpeg = os.environ.get("FFMPEG", "ffmpeg")
    tmpdir = Path("/tmp/feedback-keypose-video")
    if tmpdir.exists():
        shutil.rmtree(tmpdir)
    tmpdir.mkdir(parents=True)
    for i, f in enumerate(frames):
        f.save(tmpdir / f"v{i:04d}.png")
    mp4 = HERE / "feedback-walk-keypose-swagger-preview.mp4"
    subprocess.run([
        ffmpeg, "-v", "error", "-y", "-framerate", str(OUT_FPS), "-i", str(tmpdir / "v%04d.png"),
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "16", "-movflags", "+faststart", str(mp4),
    ], check=True)

    # Seam: last key -> first key, exactly what the player cuts between.
    a = np.asarray(draw_floor(seq[-1]).convert("RGB")).astype(np.int16)
    b = np.asarray(draw_floor(seq[0]).convert("RGB")).astype(np.int16)
    d = np.abs(a - b).max(2)
    changed = d > 8
    steps = []
    for i in range(len(seq)):
        x = np.asarray(draw_floor(seq[i]).convert("RGB")).astype(np.int16)
        y = np.asarray(draw_floor(seq[(i + 1) % len(seq)]).convert("RGB")).astype(np.int16)
        dd = np.abs(x - y).max(2)
        steps.append(float((dd > 8).mean() * 100))
    seam = {
        "changedPixelPct": round(float(changed.mean() * 100), 2),
        "meanDiffChangedPixels": round(float(d[changed].mean()), 2) if changed.any() else 0.0,
        "medianKeyStepChangedPct": round(float(np.median(steps)), 2),
        "maxKeyStepChangedPct": round(float(np.max(steps)), 2),
        "seamVsMedianKeyStep": round(float(changed.mean() * 100 / np.median(steps)), 2),
    }
    diff_img = np.zeros((*d.shape, 3), np.uint8)
    diff_img[..., 0] = np.clip(d * 2, 0, 255)
    diff_img[changed, 1] = 90
    Image.fromarray(diff_img).save(HERE / "seam-diff.png")

    manifest = {
        "asset": SOURCE.name,
        "sourceSha256": SOURCE_SHA256,
        "sourceFrameRange": [start, start + length - 1],
        "cycleFrames": length,
        "sourceFps": SOURCE_FPS,
        "uniformScale": round(scale, 4),
        "targetHeightPx": TARGET_HEIGHT,
        "floorY": FLOOR_Y,
        "panel": [PANEL_W, PANEL_H],
        "holdFrames": HOLD_FRAMES,
        "outputFps": OUT_FPS,
        "cycles": CYCLES,
        "keys": entries,
        "seam": seam,
        "mirrored": False,
        "generated": False,
    }
    (HERE / "keyposes-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({k: v for k, v in manifest.items() if k != "keys"}, indent=2))
    for e in entries:
        print(e["index"], e["phase"], e["level"], "f" + str(e["srcFrame"]),
              "span", e["ankleSpanPx"], "h", e["heightVsLoopMedianPx"],
              "sh-hip", e["shoulderHipOffsetPx"])


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "analyze"
    analyze() if cmd == "analyze" else build()
