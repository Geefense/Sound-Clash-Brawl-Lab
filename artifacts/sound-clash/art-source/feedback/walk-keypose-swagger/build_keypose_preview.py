#!/usr/bin/env python3
"""Rough key-pose swagger preview for Feedback, extracted from the saved walk test.

Nothing is generated by a model. Every pose is a cleaned, scaled and
floor-aligned crop of a frame in feedback-walk-flow-test.mp4. Whole-character
mirroring is never applied, so the mic stays in the hand it is drawn in.

Usage:
    FFMPEG=/path/to/ffmpeg python3 build_keypose_preview.py analyze
    FFMPEG=/path/to/ffmpeg python3 build_keypose_preview.py build
"""

